async function main() {
  console.log(`Bắt đầu xử lý ${ITEMS_SPEC.length} ảnh lookbook studio...`);
  const results = [];

  for (const item of ITEMS_SPEC) {
    const srcPath = path.join(ASSETS_DIR, item.file);
    if (!fs.existsSync(srcPath)) {
      console.error(`Không tìm thấy file: ${srcPath}`);
      continue;
    }

    const baseName = item.id;
    const thumbName = `${baseName}-thumb.webp`;
    const fullWebpName = `${baseName}.webp`;
    const thumbPath = path.join(OUT_PUBLIC_DIR, thumbName);
    const fullPath = path.join(OUT_PUBLIC_DIR, fullWebpName);

    // 1. Generate WebP thumbnail (600px width, 3:4 ratio)
    await sharp(srcPath).resize(600, 800, { fit: "cover" }).webp({ quality: 84 }).toFile(thumbPath);

    // 2. Generate Full WebP (1200px width, 3:4 ratio)
    await sharp(srcPath).resize(1200, 1600, { fit: "cover" }).webp({ quality: 88 }).toFile(fullPath);

    results.push({
      ...item,
      imageThumb: `/menu/lookbook/${thumbName}`,
      imageFull: `/menu/lookbook/${fullWebpName}`,
    });

    console.log(`✓ Đã tối ưu: ${item.name} (${item.file})`);
  }

  // Write structured JSON data
  const dataPath = path.join(OUT_DATA_DIR, "menu-lookbook.json");
  fs.writeFileSync(dataPath, JSON.stringify(results, null, 2), "utf8");
  console.log(`Đã xuất dữ liệu menu lookbook: ${dataPath}`);
}

main().catch(console.error);
