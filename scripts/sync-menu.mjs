#!/usr/bin/env node
// Copies the shop's menu from its Odoo (the till's own dishes, groups and counter prices) into
// src/data/odoo/menu.json, through the Boongee MCP server (../odoo/mcp-boongee: `list_menu` for the dishes and prices,
// `get_dish` for each dish's group on the till and its recipe, from which each drink gets a plain line under its
// name: src/lib/menu/describe.ts). Only dishes shown on the till are kept. Run after the menu changes in
// Odoo: `npm run sync-menu`. The file is committed, so building the site never needs Odoo.
//
//   BOONGEE_MCP   the server's command (default: ../odoo/mcp-boongee/run.sh prod). On the office network, which
//                 blocks the shop's sslip.io address, point it at a launcher that reaches Odoo through an SSH tunnel.
//
// The API key stays where scripts/mcp-key.sh put it (../odoo/mcp-boongee/.env.<profile>): this script never reads it.

import { spawn } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { createInterface } from "node:readline";
import { fileURLToPath } from "node:url";
import { describeDish } from "../src/lib/menu/describe.ts";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const COMMAND = (process.env.BOONGEE_MCP ?? path.join(ROOT, "..", "odoo", "mcp-boongee", "run.sh") + " prod").split(
  " ",
);
const OUT = path.join(ROOT, "src", "data", "odoo", "menu.json");
/** Till groups that are bookkeeping, not menu sections. */
const NOT_ON_MENU = new Set(["Món mới (từ bảng cost)"]);

/** A minimal MCP client over stdio: initialize, then one tools/call at a time. */
function connect(command) {
  const child = spawn(command[0], command.slice(1), { stdio: ["pipe", "pipe", "pipe"] });
  let stderr = "";
  child.stderr.on("data", (chunk) => (stderr += chunk));
  const waiting = new Map();
  createInterface({ input: child.stdout }).on("line", (line) => {
    const message = JSON.parse(line);
    waiting.get(message.id)?.(message);
    waiting.delete(message.id);
  });
  child.on("exit", (code) => {
    for (const resolve of waiting.values()) resolve({ error: { message: `MCP server exited ${code}: ${stderr}` } });
  });
  let id = 0;
  const request = (method, params) =>
    new Promise((resolve) => {
      const n = ++id;
      waiting.set(n, resolve);
      child.stdin.write(JSON.stringify({ jsonrpc: "2.0", id: n, method, params }) + "\n");
    });
  return {
    async start() {
      const init = await request("initialize", {
        protocolVersion: "2025-06-18",
        capabilities: {},
        clientInfo: { name: "boongee-landing-sync-menu", version: "1" },
      });
      if (init.error) throw new Error(init.error.message);
      child.stdin.write(JSON.stringify({ jsonrpc: "2.0", method: "notifications/initialized" }) + "\n");
    },
    async call(name, args = {}) {
      const reply = await request("tools/call", { name, arguments: args });
      const text = reply.result?.content?.map((c) => c.text).join("") ?? "";
      if (reply.error || reply.result?.isError) throw new Error(`${name}: ${reply.error?.message ?? text}`);
      return JSON.parse(text);
    },
    close: () => child.kill(),
  };
}

const odoo = connect(COMMAND);
try {
  await odoo.start();
  const { pos_categories: groups } = await odoo.call("get_settings");
  const { items } = await odoo.call("list_menu");
  const dishes = new Map(); // name → { kind, prices: { size: thousand đồng } }, in Odoo's order
  for (const item of items) {
    if (!item.on_till) continue;
    const dish = dishes.get(item.dish) ?? { kind: item.kind, prices: {} };
    dish.prices[item.size || "one"] = Math.round(item.price / 1000);
    dishes.set(item.dish, dish);
  }
  const sections = new Map(groups.filter((g) => !NOT_ON_MENU.has(g)).map((g) => [g, []]));
  const unplaced = [];
  for (const [name, dish] of dishes) {
    const detail = await odoo.call("get_dish", { dish: name });
    const group = detail.pos_categories.find((g) => sections.has(g));
    const prices = dish.prices.M ? [dish.prices.M, dish.prices.L].filter(Boolean) : [dish.prices.one];
    // the plain line under the name, from the recipe's components (packaging left out); drinks only
    const recipe = detail.variants?.[0]?.recipe ?? [];
    const note =
      dish.kind === "do-uong" ? describeDish(recipe.filter((r) => !r.is_packaging).map((r) => r.component)) : null;
    if (group) sections.get(group).push({ name, kind: dish.kind, prices, ...(note ? { note } : {}) });
    else unplaced.push(name);
  }
  const menu = {
    _readme:
      "Generated by scripts/sync-menu.mjs from the shop's Odoo (list_menu, get_dish). Do not edit: change the dish in Odoo, then npm run sync-menu.",
    syncedOn: new Date().toISOString().slice(0, 10),
    groups: [...sections].filter(([, list]) => list.length).map(([title, list]) => ({ title, items: list })),
  };
  mkdirSync(path.dirname(OUT), { recursive: true });
  writeFileSync(OUT, JSON.stringify(menu, null, 2) + "\n");
  console.log(`ok: ${path.relative(ROOT, OUT)} (${dishes.size} món trên quầy)`);
  if (unplaced.length) console.warn(`Món chưa có nhóm thực đơn (bỏ qua): ${unplaced.join(", ")}`);
} finally {
  odoo.close();
}
